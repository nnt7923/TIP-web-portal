// Run only against the isolated notification branch; never falls back to .env.
require('dotenv').config({ path: '.env.notifications.local', override: true, quiet: true });
require('reflect-metadata');
const assert = require('node:assert/strict');
const { randomUUID } = require('node:crypto');
const { PrismaClient } = require('@prisma/client');
const { Test } = require('@nestjs/testing');
const { ValidationPipe, UnauthorizedException } = require('@nestjs/common');
const request = require('supertest');
const { NotificationsService } = require('../dist/modules/notifications/notifications.service');
const { NotificationEventsService } = require('../dist/modules/notifications/notification-events.service');
const { NotificationsController } = require('../dist/modules/notifications/notifications.controller');
const { JwtAuthGuard } = require('../dist/modules/auth/guards/jwt-auth-guard');
const { EnrollmentService } = require('../dist/modules/student-enrollment/enrollment.service');
const { ApplicationService } = require('../dist/modules/application/application.service');
const { PlacementService } = require('../dist/modules/placement/placement.service');
const { InternshipPeriodService } = require('../dist/modules/internship-period/internship-period.service');
const { SchoolUserService } = require('../dist/modules/schooluser/schooluser.service');
const { CompanyUserService } = require('../dist/modules/companyuser/company-user.service');
const { SystemAdminService } = require('../dist/modules/system-admin/system-admin.service');
const { AuthService } = require('../dist/modules/auth/auth.service');
const { createClientApiPolicy } = require('../dist/common/client-api-policy');
const endpoint = new URL(process.env.DATABASE_URL || 'http://missing').hostname;
assert.equal(endpoint, 'ep-frosty-grass-b5tfrrug.c-7.us-east-2.aws.neon.tech', 'Use the isolated notification test branch');
const prisma = new PrismaClient({ transactionOptions: { timeout: 60000, maxWait: 15000 } });
const notifications = new NotificationsService(prisma);
const events = new NotificationEventsService(notifications);
const marker = `notifications-${randomUUID()}`;
const ids = [], schools = [], companies = [];
let app, checks = 0;
const include = { schoolUser: true, companyUser: true, student: true };
const account = async (suffix, extra = {}) => {
  const row = await prisma.account.create({ data: { username: marker + suffix, email: marker + suffix + '@example.invalid', fullName: 'Notification test', passwordHash: 'not-a-password', emailVerifiedAt: new Date(), ...extra }, include });
  ids.push(row.id); return row;
};
const count = async (who, where = {}) => prisma.notification.count({ where: { recipientAccountId: who.id, ...where } });
const check = (actual, expected) => { assert.deepEqual(actual, expected); checks++; };

async function main() {
  const school = await prisma.university.create({ data: { name: marker, code: marker, status: 'VERIFIED', majors: { create: { name: 'Computing' } } }, include: { majors: true } }); schools.push(school.id);
  const otherSchool = await prisma.university.create({ data: { name: marker + '-other', code: marker + '-other', status: 'VERIFIED' } }); schools.push(otherSchool.id);
  const company = await prisma.company.create({ data: { name: marker, status: 'VERIFIED' } }); companies.push(company.id);
  const schoolProfile = (role, universityId = school.id, status = 'ACTIVE') => ({ create: { role, universityId, status } });
  const companyProfile = (role = 'COMPANY_ADMIN', status = 'ACTIVE') => ({ create: { role, companyId: company.id, status } });
  const admin = await account('-admin', { schoolUser: schoolProfile('UNIVERSITY_ADMIN') });
  const staff = await account('-staff', { schoolUser: schoolProfile('STAFF') });
  const teacher = await account('-teacher', { schoolUser: schoolProfile('UNIVERSITY_SUPERVISOR') });
  const teacher2 = await account('-teacher2', { schoolUser: schoolProfile('UNIVERSITY_SUPERVISOR') });
  const otherAdmin = await account('-other', { schoolUser: schoolProfile('UNIVERSITY_ADMIN', otherSchool.id) });
  const inactiveAdmin = await account('-inactive', { schoolUser: schoolProfile('UNIVERSITY_ADMIN', school.id, 'INACTIVE') });
  const companyAdmin = await account('-company', { companyUser: companyProfile() });
  const mentor = await account('-mentor', { companyUser: companyProfile('STAFF') });
  const multi = await account('-multi', { companyUser: companyProfile(), schoolUser: schoolProfile('STAFF') });
  const sys = await account('-system', { globalRole: 'SYSTEM_ADMIN' });
  const personal = await account('-personal');
  const identities = { personal, admin, otherAdmin };
  const module = await Test.createTestingModule({ controllers: [NotificationsController], providers: [{ provide: NotificationsService, useValue: notifications }] })
    .overrideGuard(JwtAuthGuard).useValue({ canActivate(context) {
      const req = context.switchToHttp().getRequest(); req.user = identities[req.headers.authorization];
      if (!req.user) throw new UnauthorizedException(); return true;
    } }).compile();
  app = module.createNestApplication();
  app.useGlobalPipes(new ValidationPipe({ transform: true, whitelist: true, forbidNonWhitelisted: true }));
  await app.init();
  const http = request(app.getHttpServer());
  const send = async (method, path, who, status = 200) => {
    let req = http[method](path); if (who) req = req.set('Authorization', who);
    const result = await req; assert.equal(result.status, status, JSON.stringify(result.body)); checks++; return result.body;
  };
  check(createClientApiPolicy([NotificationsController])('GET', '/notifications'), true);
  await send('get', '/notifications', undefined, 401);
  await send('get', '/notifications?limit=101', 'admin', 400);
  await send('get', '/notifications?filter=false', 'admin', 400);
  await send('get', '/notifications?recipientAccountId=' + personal.id, 'admin', 400);
  const enrollment = new EnrollmentService(prisma, events);
  const input = { universityId: school.id, majorId: school.majors[0].id, studentCode: marker, className: 'SE01', semester: 2 };
  const first = await enrollment.submit(personal, input);
  check(await count(admin, { entityId: first.id }), 1);
  check(await count(otherAdmin, { entityId: first.id }), 0);
  check(await count(inactiveAdmin, { entityId: first.id }), 0);
  await enrollment.review(admin, first.id, { decision: 'REJECTED', reason: 'Private reason must not be in notifications' });
  let inbox = await send('get', '/notifications?filter=unread', 'personal');
  check(inbox.total, 1); check(inbox.data[0].body.includes('Private reason'), false);
  check('recipientAccountId' in inbox.data[0], false);
  await send('patch', `/notifications/${inbox.data[0].id}/read`, 'otherAdmin', 404);
  const read = await send('patch', `/notifications/${inbox.data[0].id}/read`, 'personal');
  check((await send('patch', `/notifications/${read.id}/read`, 'personal')).readAt, read.readAt);
  check((await send('get', '/notifications/unread-count', 'personal')).count, 0);
  const second = await enrollment.submit(personal, input);
  await enrollment.review(admin, second.id, { decision: 'APPROVED' });
  const student = await prisma.account.findUniqueOrThrow({ where: { id: personal.id }, include });
  const opportunity = await prisma.opportunity.create({ data: { companyId: company.id, title: 'Intern', type: 'INTERNSHIP', description: 'Test', status: 'OPEN', applicationDeadline: new Date(Date.now() + 86400000), vacancies: 5 } });
  const applications = new ApplicationService(prisma, events);
  const application = await applications.create(student, { opportunityId: opportunity.id });
  check(await count(companyAdmin, { entityId: application.id }), 1);
  check(await count(mentor, { entityId: application.id }), 0);
  for (const status of ['REVIEWING', 'ACCEPTED']) await applications.updateStatus(companyAdmin, application.id, { status });
  check(await count(student, { entityId: application.id }), 2);
  await assert.rejects(applications.updateStatus(companyAdmin, application.id, { status: 'ACCEPTED' }));
  check(await count(student, { entityId: application.id }), 2);
  const opportunity2 = await prisma.opportunity.create({ data: { companyId: company.id, title: 'Intern 2', type: 'INTERNSHIP', description: 'Test', status: 'OPEN', applicationDeadline: new Date(Date.now() + 86400000) } });
  const withdrawn = await applications.create(student, { opportunityId: opportunity2.id });
  await applications.withdraw(student, withdrawn.id);
  check(await count(companyAdmin, { entityId: withdrawn.id, type: 'APPLICATION_WITHDRAWN' }), 1);
  const opportunity3 = await prisma.opportunity.create({ data: { companyId: company.id, title: 'Intern 3', type: 'INTERNSHIP', description: 'Test', status: 'OPEN', applicationDeadline: new Date(Date.now() + 86400000) } });
  const rejected = await applications.create(student, { opportunityId: opportunity3.id });
  await applications.updateStatus(companyAdmin, rejected.id, { status: 'REJECTED' });
  check(await count(student, { entityId: rejected.id, type: 'APPLICATION_REJECTED' }), 1);
  const now = Date.now();
  const year = await prisma.academicYear.create({ data: { universityId: school.id, name: marker, startDate: new Date(now - 86400000), endDate: new Date(now + 86400000 * 120) } });
  const period = await prisma.internshipPeriod.create({ data: { universityId: school.id, academicYearId: year.id, name: marker, periodNumber: 1, status: 'OPEN', startDate: new Date(now + 86400000), endDate: new Date(now + 86400000 * 90), applyStartDate: new Date(now - 86400000), applyEndDate: new Date(now + 86400000) } });
  await new InternshipPeriodService(prisma, events).registerStudent(admin, period.id, { studentId: student.student.id });
  check(await count(student, { type: 'INTERNSHIP_REGISTERED' }), 1);
  const placements = new PlacementService(prisma, events);
  const placement = await placements.create(admin, { studentId: student.student.id, companyId: company.id, positionTitle: 'Developer', startDate: new Date(now - 86400000 * 2).toISOString(), endDate: new Date(now - 86400000).toISOString(), universitySupervisorId: teacher.schoolUser.id });
  check(await count(student, { entityId: placement.id }), 1);
  check(await count(teacher, { entityId: placement.id }), 1);
  check(await count(admin, { entityId: placement.id }), 0);
  await placements.update(admin, placement.id, { universitySupervisorId: teacher2.schoolUser.id });
  check(await count(teacher, { entityId: placement.id }), 2);
  check(await count(teacher2, { entityId: placement.id }), 1);
  const beforeNoop = await prisma.notification.count({ where: { entityId: placement.id } });
  await placements.update(admin, placement.id, { universitySupervisorId: teacher2.schoolUser.id });
  check(await prisma.notification.count({ where: { entityId: placement.id } }), beforeNoop);
  await placements.confirm(companyAdmin, placement.id, { companySupervisorId: mentor.companyUser.id });
  check(await count(multi, { entityId: placement.id }), 2); // create + confirm; two roles still one recipient
  check(await count(staff, { entityId: placement.id }), 1);
  await placements.assignCompanySupervisor(companyAdmin, placement.id, { companySupervisorId: null });
  check(await count(mentor, { entityId: placement.id }), 2);
  await placements.updateStatus(admin, placement.id, { status: 'IN_PROGRESS' });
  await placements.updateStatus(admin, placement.id, { status: 'COMPLETED' });
  const pending = await account('-pending', { emailVerifiedAt: null, schoolUser: schoolProfile('STAFF', school.id, 'PENDING') });
  const auth = new AuthService(prisma, {}, { get: () => undefined }, {}, {}, events);
  auth.consumeOtp = async () => true;
  auth.redisService = { connection: { del: async () => 1 } };
  await auth.verifyOtp({ email: pending.email, otp: '123456' });
  await auth.verifyOtp({ email: pending.email, otp: '123456' });
  check(await count(sys, { entityId: pending.schoolUser.id, type: 'PROFILE_PENDING' }), 1);
  check(await count(admin, { entityId: pending.schoolUser.id, type: 'PROFILE_PENDING' }), 1);
  await new SchoolUserService(prisma, { logoutAll: async () => {} }, events).approve(admin, pending.schoolUser.id, { role: 'STAFF' });
  check(await count(pending, { type: 'PROFILE_APPROVED' }), 1);
  const pendingCompany = await account('-pending-company', { companyUser: companyProfile('STAFF', 'PENDING') });
  await prisma.$transaction(tx => events.pendingProfile(tx, pendingCompany.id));
  check(await count(companyAdmin, { entityId: pendingCompany.companyUser.id }), 1);
  await new CompanyUserService(prisma, { logoutAll: async () => {} }, events).approve(companyAdmin, pendingCompany.companyUser.id, { role: 'STAFF' });
  check(await count(pendingCompany, { type: 'PROFILE_APPROVED' }), 1);
  const pendingSchool = await prisma.university.create({ data: { name: marker + '-pending', code: marker + '-pending' } }); schools.push(pendingSchool.id);
  const pendingUniversity = await account('-university', { schoolUser: schoolProfile('UNIVERSITY_ADMIN', pendingSchool.id, 'PENDING') });
  await prisma.$transaction(tx => events.pendingProfile(tx, pendingUniversity.id));
  check(await count(sys, { entityId: pendingUniversity.id }), 1);
  await new SystemAdminService(prisma, { logoutAll: async () => {} }, events).approveUniversityRegistration(sys.id, pendingUniversity.id);
  check(await count(pendingUniversity, { type: 'PROFILE_APPROVED' }), 1);
  const event = { eventId: randomUUID(), actorId: admin.id, type: 'TEST', title: 'Test', body: 'Test', entityType: 'AccountProfile', entityId: student.id, recipients: [{ id: student.id }, { id: student.id }, { id: admin.id }] };
  await Promise.all([prisma.$transaction(tx => notifications.emit(tx, event)), prisma.$transaction(tx => notifications.emit(tx, event))]);
  check(await count(student, { eventId: event.eventId }), 1);
  check(await count(admin, { eventId: event.eventId }), 0);
  const rollbackEvent = { ...event, eventId: randomUUID() };
  await assert.rejects(prisma.$transaction(async tx => { await notifications.emit(tx, rollbackEvent); throw new Error('Rollback'); }));
  check(await count(student, { eventId: rollbackEvent.eventId }), 0);
  const failing = new EnrollmentService(prisma, { enrollment: async () => { throw new Error('Notification write failed'); } });
  const rollbackUser = await account('-rollback');
  await assert.rejects(failing.submit(rollbackUser, { ...input, studentCode: marker + '-rollback' }));
  check(await prisma.studentEnrollment.count({ where: { accountId: rollbackUser.id } }), 0);
  const cutoff = new Date();
  await prisma.notification.create({ data: { recipientAccountId: student.id, eventId: randomUUID(), type: 'TEST', title: 'New', body: 'New', entityType: 'AccountProfile', entityId: student.id, createdAt: new Date(cutoff.getTime() + 1000) } });
  await notifications.readAll(student.id, cutoff);
  check((await notifications.unreadCount(student.id)).count, 1);
  await send('patch', '/notifications/read-all', 'personal');
  const ordered = await send('get', '/notifications?limit=2', 'personal');
  check(ordered.data.length, 2); check(ordered.limit, 2);
  const page2 = await send('get', '/notifications?limit=2&page=2', 'personal');
  check(page2.data.some(row => ordered.data.some(first => first.id === row.id)), false);
  console.log(`Notifications integration: ${checks} assertions passed (isolated database).`);
}

main().finally(async () => {
  await app?.close();
  // Only delete fixtures created by this run, in FK order.
  await prisma.notification.deleteMany({ where: { OR: [{ recipientAccountId: { in: ids } }, { entityId: { in: ids } }, { body: 'Test', entityId: { in: ids } }, { eventId: { startsWith: 'profile-pending:' }, entityId: { in: (await prisma.schoolUser.findMany({ where: { accountId: { in: ids } }, select: { id: true } })).map(row => row.id) } }, { entityId: { in: (await prisma.companyUser.findMany({ where: { accountId: { in: ids } }, select: { id: true } })).map(row => row.id) } }] } });
  await prisma.auditLog.deleteMany({ where: { actorId: { in: ids } } });
  await prisma.placement.deleteMany({ where: { universityId: { in: schools } } });
  await prisma.application.deleteMany({ where: { universityId: { in: schools } } });
  await prisma.studentInternship.deleteMany({ where: { student: { universityId: { in: schools } } } });
  await prisma.studentEnrollment.deleteMany({ where: { accountId: { in: ids } } });
  await prisma.account.deleteMany({ where: { id: { in: ids } } });
  await prisma.internshipPeriod.deleteMany({ where: { universityId: { in: schools } } });
  await prisma.academicYear.deleteMany({ where: { universityId: { in: schools } } });
  await prisma.major.deleteMany({ where: { universityId: { in: schools } } });
  await prisma.university.deleteMany({ where: { id: { in: schools } } });
  await prisma.opportunity.deleteMany({ where: { companyId: { in: companies } } });
  await prisma.company.deleteMany({ where: { id: { in: companies } } });
  await prisma.$disconnect();
}).catch(error => { console.error(error); process.exitCode = 1; });
